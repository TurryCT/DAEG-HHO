result_3p.methodName = 'Three-parameter inversion';
result_3p.parameterMode = 'Vs-H-Vp inversion';

result_3p.Npop = Npop;
result_3p.Max_it = Max_it;
result_3p.Nrun = Nrun;
result_3p.nD = nD;

if exist('n_mode', 'var')
    result_3p.n_mode = n_mode;
end

result_3p.lb = lb(:).';
result_3p.ub = ub(:).';

result_3p.VS_true = VS_true(:).';
result_3p.VP_true = VP_true(:).';
result_3p.H_true = H_true(:).';
result_3p.den = den(:).';

result_3p.x_all = x_all_dlh;
result_3p.x_mean = x_mean_dlh(:).';
result_3p.x_best = x_best_dlh(:).';

result_3p.f_all = f_all_dlh(:);
result_3p.f_best = min(f_all_dlh);
result_3p.idx_best = idx_best;

result_3p.hist_all = hist_all_dlh;

result_3p.hist_mean = mean( ...
    hist_all_dlh, ...
    1, ...
    'omitnan');

result_3p.hist_median = median( ...
    hist_all_dlh, ...
    1, ...
    'omitnan');

result_3p.iteration = 1:Max_it;

result_3p.freq = freq(:);
result_3p.pv_obs = pv(:);
result_3p.pv_true = pv_true(:);
result_3p.pv_mean = pv_mean(:);

save('result_3pmn.mat', 'result_3p');