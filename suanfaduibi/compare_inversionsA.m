function SABO_all = infer_sabo_positions( ...
    out1, out3, Nrun, nD)

SABO_all = nan(Nrun, nD);

candidates = {out1, out3};

for k = 1:numel(candidates)

    temp = candidates{k};

    if isempty(temp) || ~isnumeric(temp)
        continue;
    end

    sz = size(temp);

    if isequal(sz, [Nrun, nD])

        SABO_all = temp;
        return;

    elseif isequal(sz, [nD, Nrun])

        SABO_all = temp.';
        return;

    elseif isvector(temp) && numel(temp) == nD

        SABO_all = repmat(temp(:).', Nrun, 1);
        return;
    end
end

warning( ...
    ['SABO parameter results could not be identified as an ', ...
     'Nrun-by-nD matrix. SABO parameter RMSE values will be NaN.']);

