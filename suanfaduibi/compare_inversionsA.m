function curveOut = fit_curve_length(curveIn, targetLen)

curveIn = curveIn(:).';

curveOut = nan(1, targetLen);

if isempty(curveIn)
    return;
end

n = min(numel(curveIn), targetLen);

curveOut(1:n) = curveIn(1:n);

if n < targetLen
    curveOut(n + 1:end) = curveIn(n);
end

end


function f = safe_objective(x, fitness_func)

if isempty(x) || any(~isfinite(x))
    f = NaN;
    return;
end

try

    temp = fitness_func(x);

    if isempty(temp) || ...
            ~isscalar(temp) || ...
            ~isreal(temp) || ...
            ~isfinite(temp)

        f = NaN;

    else

        f = double(temp);
    end

catch

    f = NaN;
end

end


function rmseVal = parameter_rmse(paramMat, trueParam)

trueParam = trueParam(:).';

nRun = size(paramMat, 1);

rmseVal = nan(nRun, 1);

for i = 1:nRun

    x = paramMat(i, :);

    if any(~isfinite(x))

        rmseVal(i) = NaN;

    else

        rmseVal(i) = ...
            sqrt(mean((x - trueParam) .^ 2));
    end
end

end


function pv = safe_phase_curve(freq, x, den)

freq = freq(:);

pv = nan(size(freq));

if isempty(x) || any(~isfinite(x))
    return;
end

try

    temp = calcbase( ...
        freq, ...
        x(1:4), ...
        x(5:7), ...
        x(8:11), ...
        den);

    temp = temp(:);

    n = min(numel(temp), numel(freq));

    pv(1:n) = temp(1:n);

catch

    pv(:) = NaN;
end

end


